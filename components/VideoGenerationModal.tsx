
import React from 'react';
import { useStory } from '../context/StoryContext.tsx';

export const VideoGenerationModal: React.FC = () => {
    const { 
        isGeneratingVideo, 
        videoGenerationStatus, 
        generatedVideoUrl, 
        clearGeneratedVideo,
        story,
        activeChapterId
    } = useStory();

    const activeChapter = story?.chapters.find(c => c.id === activeChapterId);
    const videoUrlToShow = generatedVideoUrl || activeChapter?.videoUrl;

    if (!isGeneratingVideo && !videoUrlToShow) return null;

    return (
        <div className="fixed inset-0 z-[110] flex items-center justify-center p-4 bg-black/90 backdrop-blur-xl animate-fadeIn">
            <div className="bg-gray-900 border border-gray-800 rounded-2xl w-full max-w-4xl flex flex-col shadow-2xl overflow-hidden relative">
                
                {/* Generation Loading State */}
                {isGeneratingVideo && (
                    <div className="p-12 flex flex-col items-center justify-center text-center space-y-8 animate-fadeIn">
                        <div className="relative">
                            <div className="w-24 h-24 border-4 border-blue-500/20 border-t-blue-500 rounded-full animate-spin"></div>
                            <div className="absolute inset-0 flex items-center justify-center">
                                <svg className="w-8 h-8 text-blue-400 animate-pulse" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                                    <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M15 10l4.553-2.276A1 1 0 0121 8.618v6.764a1 1 0 01-1.447.894L15 14M5 18h8a2 2 0 002-2V8a2 2 0 00-2-2H5a2 2 0 00-2 2v8a2 2 0 002 2z" />
                                </svg>
                            </div>
                        </div>
                        
                        <div className="space-y-3">
                            <h3 className="text-2xl font-serif font-bold text-white tracking-wide">Aetheria Cinematic Engine</h3>
                            <p className="text-blue-400 font-medium animate-pulse text-sm">
                                {videoGenerationStatus || "Đang khởi tạo bối cảnh..."}
                            </p>
                            <p className="text-[10px] text-gray-500 uppercase tracking-widest max-w-sm mx-auto">
                                Quá trình này có thể mất vài phút. Hãy thư giãn trong khi chúng tôi hình ảnh hóa tác phẩm của bạn.
                            </p>
                        </div>

                        {/* Aesthetic decorative bars */}
                        <div className="flex gap-1">
                            {[...Array(5)].map((_, i) => (
                                <div key={i} className="w-1 h-8 bg-blue-500/20 rounded-full overflow-hidden">
                                    <div className="w-full h-full bg-blue-400 animate-bounce" style={{ animationDelay: `${i * 0.1}s` }}></div>
                                </div>
                            ))}
                        </div>
                    </div>
                )}

                {/* Video Result State */}
                {!isGeneratingVideo && videoUrlToShow && (
                    <div className="flex flex-col animate-fadeIn">
                        <div className="p-4 border-b border-gray-800 flex justify-between items-center bg-gray-850/50">
                            <div>
                                <h2 className="text-lg font-bold text-white flex items-center gap-2">
                                    <svg className="w-5 h-5 text-blue-400" fill="none" viewBox="0 0 24 24" stroke="currentColor"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M14.752 11.168l-3.197-2.132A1 1 0 0010 9.87v4.263a1 1 0 001.555.832l3.197-2.132a1 1 0 000-1.664z" /><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M21 12a9 9 0 11-18 0 9 9 0 0118 0z" /></svg>
                                    Phim minh họa: {activeChapter?.title}
                                </h2>
                                <p className="text-[10px] text-gray-500 uppercase font-black">Generated by Veo 3.1 Fast</p>
                            </div>
                            <button onClick={clearGeneratedVideo} className="p-2 text-gray-500 hover:text-white bg-gray-800 rounded-full transition-colors">
                                <svg className="w-6 h-6" fill="none" viewBox="0 0 24 24" stroke="currentColor"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" /></svg>
                            </button>
                        </div>
                        
                        <div className="aspect-video bg-black relative flex items-center justify-center">
                            <video 
                                src={videoUrlToShow} 
                                controls 
                                className="w-full h-full object-contain shadow-2xl"
                                autoPlay
                            />
                        </div>

                        <div className="p-6 bg-gray-900 border-t border-gray-800 flex justify-between items-center">
                            <div className="text-xs text-gray-500 italic flex items-center gap-2">
                                <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M13 16h-1v-4h-1m1-4h.01M21 12a9 9 0 11-18 0 9 9 0 0118 0z" /></svg>
                                Video này là một phiên bản dựng sẵn minh họa cho không khí của chương.
                            </div>
                            <div className="flex gap-3">
                                <a 
                                    href={videoUrlToShow} 
                                    download={`${activeChapter?.title || 'trailer'}.mp4`}
                                    className="px-6 py-2.5 bg-gray-800 text-gray-300 rounded-xl font-bold text-xs hover:bg-gray-700 transition-all border border-gray-700"
                                >
                                    Tải về (MP4)
                                </a>
                                <button 
                                    onClick={clearGeneratedVideo} 
                                    className="px-8 py-2.5 bg-blue-600 text-white rounded-xl font-black text-xs shadow-lg hover:bg-blue-500 transition-all"
                                >
                                    Tuyệt vời
                                </button>
                            </div>
                        </div>
                    </div>
                )}
            </div>
        </div>
    );
};
